def test_web_repair_session_windows():
    session = _load(
        PKG / "tmux" / "autogenerated" / "base_station_web_repair-default.yaml"
    )
    names = [w["window_name"] for w in session["windows"]]
    for name in ["prior_dsg", "planning", "console", "fleetlink_base", "sam3_query",
                 "global_status", "tf_relay"]:  # fmt: skip
        assert name in names
    planning = next(w for w in session["windows"] if w["window_name"] == "planning")
    assert len(planning["panes"]) == 1
    assert "launch_rviz" not in planning["panes"][0]["shell"]
    assert "launch_omniplanner_repair:=true" in planning["panes"][0]["shell"]
    assert "nlu_rviz_instruction_panel" not in session["nodes_to_monitor"]
    console = next(w for w in session["windows"] if w["window_name"] == "console")
    assert (
        "--neo4j live=${ADT4_NEO4J_URI:-bolt://localhost:7687}"
        in console["panes"][0]["shell"]
    )
    plain = _load(PKG / "tmux" / "autogenerated" / "base_station_web-default.yaml")
    plain_console = next(w for w in plain["windows"] if w["window_name"] == "console")
    assert "--neo4j" not in plain_console["panes"][0]["shell"]
