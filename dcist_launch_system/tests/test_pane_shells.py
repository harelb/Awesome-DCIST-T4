"""Generated tmux sessions run every pane as its own process (no send-keys).

tmuxp types `shell_command_before` / pane commands with `tmux send-keys`, which
races slow shells; generate_configs.convert_to_pane_shells turns every pane into a
pane-level ``shell: zsh -ic '<setup> && <cmd>; exec zsh'`` instead.
"""

import os
import pathlib
import shlex
import shutil
import subprocess
import sys

import pytest
import yaml

PKG = pathlib.Path(__file__).resolve().parents[1]
GEN_DIR = PKG / "config_generation"
COMPONENTS = GEN_DIR / "launch_components"
SESSIONS = sorted((PKG / "tmux" / "autogenerated").glob("*.yaml"))
SETUP = "source ${ADT4_WS}/install/setup.zsh"

sys.path.insert(0, str(GEN_DIR))
import generate_configs as gc  # noqa: E402

needs_zsh = pytest.mark.skipif(shutil.which("zsh") is None, reason="zsh missing")


def _load(path):
    with open(path) as f:
        return yaml.safe_load(f)


def _script(shell):
    argv = shlex.split(shell)
    assert argv[:2] == ["zsh", "-ic"], shell
    assert len(argv) == 3, shell
    return argv[2]


def _component_cmd(component, window, index):
    for w in _load(COMPONENTS / f"{component}.yaml")["windows"]:
        if w["window_name"] == window:
            return w["panes"][index]
    raise KeyError(window)


def _session_pane(session, window, index):
    for w in _load(PKG / "tmux" / "autogenerated" / f"{session}.yaml")["windows"]:
        if w["window_name"] == window:
            return w["panes"][index]
    raise KeyError(window)


def test_sessions_exist():
    assert len(SESSIONS) > 10
    assert (
        PKG / "tmux" / "autogenerated" / "base_station_web_repair-default.yaml"
    ).exists()


@pytest.mark.parametrize("path", SESSIONS, ids=lambda p: p.stem)
def test_no_pane_relies_on_send_keys(path):
    session = _load(path)
    assert "shell_command_before" not in session
    assert "shell_command" not in session
    for window in session["windows"]:
        assert "shell_command_before" not in window, window["window_name"]
        assert "window_shell" not in window, window["window_name"]
        assert window["panes"], window["window_name"]
        for pane in window["panes"]:
            assert isinstance(pane, dict), (window["window_name"], pane)
            assert pane.get("shell", "").startswith("zsh -ic "), pane
            assert not pane.get("shell_command"), pane
            assert not pane.get("shell_command_before"), pane


@needs_zsh
@pytest.mark.parametrize("path", SESSIONS, ids=lambda p: p.stem)
def test_pane_scripts_parse_in_zsh(path):
    for window in _load(path)["windows"]:
        for pane in window["panes"]:
            script = _script(pane["shell"])
            ret = subprocess.run(
                ["zsh", "-f", "-n", "-c", script], capture_output=True, text=True
            )
            assert ret.returncode == 0, (window["window_name"], ret.stderr, script)


@pytest.mark.parametrize(
    "session,component,window,index",
    [
        ("base_station_web-default", "fleetlink_base", "fleetlink_base", 0),
        ("base_station_web-default", "fleetlink_base", "fleetlink_base", 1),
        ("base_station_web-default", "console", "console", 0),
        ("base_station_web_repair-default", "console_neo4j", "console", 0),
        ("base_station_web_repair-default", "sam3_query", "sam3_query", 0),
        (
            "spot_no_relocalize-relocalize",
            "transform_publishers",
            "transform_publishers",
            0,
        ),
        (
            "spot_no_relocalize-relocalize",
            "transform_publishers",
            "transform_publishers",
            1,
        ),
        ("spot-default", "fleetlink", "fleetlink", 0),
    ],
)
def test_tricky_panes_round_trip(session, component, window, index):
    """The pane command survives quoting byte for byte."""
    cmd = _component_cmd(component, window, index)
    script = _script(_session_pane(session, window, index)["shell"])
    before = "" if component == "sam3_query" else f"{SETUP} && "
    assert script.startswith(f"{before}{cmd}; "), script
    # the command is also what lands in the interactive shell's history
    assert f"ADT4_PANE_CMD={shlex.quote(cmd)} exec zsh" in script
    assert script.endswith(" exec zsh")


def test_prepared_command_is_prefilled_not_run():
    cmd = _component_cmd("core", "core", 1)
    assert cmd.endswith("\\")
    script = _script(_session_pane("spot-default", "core", 1)["shell"])
    prepared = cmd.rstrip("\\").rstrip()
    assert script.startswith(f"{SETUP}; "), script  # setup only, cmd not run
    assert (
        f"ADT4_PANE_CMD={shlex.quote(prepared)} ADT4_PANE_PREFILL=1 exec zsh" in script
    )


def test_convert_handles_tmuxp_shorthands():
    session = {
        "shell_command_before": "echo session",
        "windows": [
            {
                "window_name": "w",
                "shell_command_before": ["echo a", {"cmd": "echo b"}],
                "panes": [
                    "echo one",
                    None,
                    "blank",
                    {"shell_command": ["echo x", "echo y"]},
                    {"shell": "already"},
                ],
            },
            {"window_name": "empty"},
        ],
    }
    out = gc.convert_to_pane_shells(session)
    assert "shell_command_before" not in out
    panes = out["windows"][0]["panes"]
    scripts = [_script(p["shell"]) for p in panes[:4]]
    assert scripts[0].startswith("echo session && echo a && echo b && echo one; ")
    assert scripts[1].startswith("echo session && echo a && echo b; ")
    assert scripts[2].startswith("echo session && echo a && echo b; ")
    assert scripts[3].startswith(
        "echo session && echo a && echo b && echo x && echo y; "
    )
    assert panes[4] == {"shell": "already"}
    assert _script(out["windows"][1]["panes"][0]["shell"]).startswith("echo session; ")


@needs_zsh
def test_fleetlink_bridge_pane_runs_with_session_env(tmp_path):
    """Run the generated bridge pane with a fake ros workspace and check its argv."""
    ws = tmp_path / "ws"
    (ws / "install").mkdir(parents=True)
    bridge = ws / "src/awesome_dcist_t4/fleetlink/bin/fleetlink-bridge"
    bridge.parent.mkdir(parents=True)
    out = tmp_path / "argv.txt"
    bridge.write_text(f'#!/bin/sh\nfor a in "$@"; do echo "$a"; done > {out}\n')
    bridge.chmod(0o755)
    (ws / "install" / "setup.zsh").write_text("export SOURCED_SETUP=1\n")

    script = _script(
        _session_pane("base_station_web-default", "fleetlink_base", 1)["shell"]
    )
    env = {
        "PATH": os.environ["PATH"],
        "HOME": str(tmp_path),  # keep the user's ~/.zshrc out of the final exec zsh
        "ADT4_WS": str(ws),
        "ADT4_FLEET_LINK": "fleetlink",
        "ADT4_FLEETLINK_CONNECT": "tcp/127.0.0.1:7450",
        "ADT4_NAMESPACE_TF": "true",
        "ADT4_ROBOT_NAME": "willow",
        "sim_time": "false",
    }
    subprocess.run(
        ["zsh", "-f", "-c", script],
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        timeout=30,
        check=False,
    )
    argv = out.read_text().splitlines()
    topo = f"{ws}/src/awesome_dcist_t4/network_diagnostics/config/topology.yaml"
    assert argv == [
        "--ros-args",
        "-r", "/tf:=/willow/tf",
        "-r", "/tf_static:=/willow/tf_static",
        "-p", "use_sim_time:=false",
        "-p", "zenoh_connect:=tcp/127.0.0.1:7450",
        "-p", f"topology:={topo}",
        "-p", f"relay_config:={ws}/src/awesome_dcist_t4/fleetlink/config/relay.yaml",
        "-p", "base_name:=willow",
    ]  # fmt: skip


