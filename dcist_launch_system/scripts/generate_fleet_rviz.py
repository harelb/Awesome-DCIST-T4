#!/usr/bin/env python3
"""Generate a fleet RViz config with one display group per robot, in its topology color.

dcist.rviz hardcodes one robot's executor/occupancy displays (topics under
``/hamilton/...``). This turns every display whose topic lives under the template
robot's namespace into a per-robot ``rviz_common/Group`` (one per ``role: robot``
machine in topology.yaml), recolors Path displays with the robot's color (see
dcist_launch_system.robot_colors), and keeps all other displays (Omniplanner Viz,
scene graphs, ...) as global.

Usage:
    dcist_launch_system/scripts/generate_fleet_rviz.py [--topology PATH]
        [--robots euclid,hamilton] [--output rviz/generated/fleet.rviz]
    ADT4_RVIZ_CONFIG=$PWD/dcist_launch_system/rviz/generated/fleet.rviz run-adt4 ...
    # (or: run-adt4 --rviz-config dcist_launch_system/rviz/generated/fleet.rviz)
"""

import argparse
import copy
import pathlib
import sys

import yaml

_PKG = pathlib.Path(__file__).resolve().parents[1]
try:
    from dcist_launch_system import robot_colors as rc
except ImportError:  # running from a source checkout without the package installed
    sys.path.insert(0, str(_PKG / "src"))
    from dcist_launch_system import robot_colors as rc

DEFAULT_TEMPLATE = _PKG / "rviz" / "dcist.rviz"
DEFAULT_OUTPUT = _PKG / "rviz" / "generated" / "fleet.rviz"
TEMPLATE_ROBOT = "hamilton"

# Display properties that hold a topic (each a {Value: topic, ...} mapping).
_TOPIC_KEYS = ("Topic", "Update Topic", "Description Topic")


def _topics(display):
    for key in _TOPIC_KEYS:
        topic = display.get(key)
        if isinstance(topic, dict) and isinstance(topic.get("Value"), str):
            yield topic


def is_robot_display(display, template_robot=TEMPLATE_ROBOT):
    prefix = f"/{template_robot}/"
    return any(t["Value"].startswith(prefix) for t in _topics(display))


def _rviz_rgb(hex_color):
    r, g, b = rc.hex_to_rgb(hex_color)
    return f"{round(r * 255)}; {round(g * 255)}; {round(b * 255)}"


def robot_group(robot, color, templates, template_robot=TEMPLATE_ROBOT):
    """Copies of ``templates`` re-namespaced to ``robot``, wrapped in a Group."""
    displays = []
    for template in templates:
        d = copy.deepcopy(template)
        for topic in _topics(d):
            topic["Value"] = topic["Value"].replace(
                f"/{template_robot}/", f"/{robot}/", 1
            )
        if d.get("Class") == "rviz_default_plugins/Path":
            d["Color"] = _rviz_rgb(color)
        displays.append(d)
    return {
        "Class": "rviz_common/Group",
        "Displays": displays,
        "Enabled": True,
        "Name": f"{robot} ({color})",
        "Value": True,
    }


def generate(config, colors, template_robot=TEMPLATE_ROBOT):
    """Return a new rviz config dict with per-robot groups for ``colors``."""
    config = copy.deepcopy(config)
    manager = config["Visualization Manager"]
    displays = manager["Displays"]
    templates = [d for d in displays if is_robot_display(d, template_robot)]
    if not templates:
        raise ValueError(f"no displays under /{template_robot}/ in the template")
    first = displays.index(templates[0])
    kept = [d for d in displays if not is_robot_display(d, template_robot)]
    groups = [
        robot_group(robot, color, templates, template_robot)
        for robot, color in colors.items()
    ]
    # Groups go where the robot-specific displays used to be.
    insert_at = sum(1 for d in displays[:first] if d in kept)
    manager["Displays"] = kept[:insert_at] + groups + kept[insert_at:]
    return config


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--topology", help="topology.yaml (default: repo copy)")
    parser.add_argument("--template", default=str(DEFAULT_TEMPLATE))
    parser.add_argument("--template-robot", default=TEMPLATE_ROBOT)
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--robots", help="comma-separated subset (default: all)")
    args = parser.parse_args(argv)

    colors = rc.robot_colors(rc.load_topology(args.topology))
    if args.robots:
        wanted = [r.strip() for r in args.robots.split(",") if r.strip()]
        missing = [r for r in wanted if r not in colors]
        if missing:
            parser.error(f"not robots in topology: {', '.join(missing)}")
        colors = {r: colors[r] for r in wanted}

    with open(args.template) as f:
        config = yaml.safe_load(f)
    out = generate(config, colors, args.template_robot)

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "w") as f:
        f.write(f"# GENERATED by {pathlib.Path(__file__).name} from {args.template}\n")
        f.write("# Do not edit; rerun the script after changing topology.yaml.\n")
        yaml.safe_dump(out, f, sort_keys=False, default_flow_style=False)
    print(f"Wrote {output} ({', '.join(f'{r}={c}' for r, c in colors.items())})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
