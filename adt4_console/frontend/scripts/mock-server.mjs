const jobs = new Map();
let jobSeq = 0;
function newJob(kind, title, script) {
  const id = `j${(++jobSeq).toString().padStart(3, "0")}`;
  const job = {id, kind, title, state: "running", created: now(), finished: null, progress: {}, log: [], confirm: null, result: null};
  jobs.set(id, job);
  const ctx = {
    log: (level, text) => (job.log.push({t: now(), level, text}), pushJob(job)),
    progress: (k, v) => ((job.progress[k] = v), pushJob(job)),
    confirm: c =>
      new Promise(res => {
        job.state = "waiting";
        job.confirm = {kind: "confirm", yes_label: "Yes", no_label: "No", required_text: null, detail: null, ...c};
        job._answer = a => {
          job.state = "running";
          job.confirm = null;
          delete job._answer;
          pushJob(job);
          res(a);
        };
        pushJob(job);
      }),
    sleep: ms => new Promise(r => setTimeout(r, ms)),
    cancelled: () => job.state === "cancelled",
  };
  (async () => {
    try {
      const result = await script(ctx);
      if (job.state !== "cancelled") {
        job.state = result === false ? "failed" : "succeeded";
        if (result !== undefined && result !== false) job.result = result;
      }
    } catch (e) {
      job.state = "failed";
      job.log.push({t: now(), level: "error", text: String(e)});
    }
    job.finished = now();
    pushJob(job);
  })();
  return id;
}
const summary = j => ({...j, log: undefined, _answer: undefined});
function pushJob(job) {
  broadcast(`job/${job.id}`, {...job, _answer: undefined});
  broadcast("jobs", [...jobs.values()].map(summary));
}


