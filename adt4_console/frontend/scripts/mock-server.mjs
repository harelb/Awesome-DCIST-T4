function decodeGraph(bytes) {
  const g = decode(bytes);
  const f32 = b => new Float32Array(Uint8Array.from(b).buffer);
  const i16 = b => new Int16Array(Uint8Array.from(b).buffer);
  const pos = f32(g.pos);
  const bbox = f32(g.bbox);
  const label = i16(g.label);
  const nodes = new Map();
  g.ids.forEach((id, i) => {
    nodes.set(id, {
      sym: id,
      layer: g.layer[i],
      part: g.part[i],
      pos: [pos[i * 3], pos[i * 3 + 1], pos[i * 3 + 2]],
      label: label[i],
      bbox: Number.isNaN(bbox[i * 6]) ? null : Array.from(bbox.slice(i * 6, i * 6 + 6)),
      name: g.names[i],
    });
  });
  return {nodes, labelspaces: g.labelspaces};
}
