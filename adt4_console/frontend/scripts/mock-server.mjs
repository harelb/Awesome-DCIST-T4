/** Split an Annex-B stream into access units at each AUD (NAL type 9). */
function splitAccessUnits(d) {
  const starts = [];
  for (let i = 0; i + 4 < d.length; i++) {
    const sc3 = d[i] === 0 && d[i + 1] === 0 && d[i + 2] === 1;
    const sc4 = d[i] === 0 && d[i + 1] === 0 && d[i + 2] === 0 && d[i + 3] === 1;
    if ((sc3 && (d[i + 3] & 0x1f) === 9) || (sc4 && (d[i + 4] & 0x1f) === 9)) {
      starts.push(i);
      i += 3;
    }
  }
  return starts.map((s, k) => {
    const au = d.subarray(s, starts[k + 1] ?? d.length);
    let key = false;
    for (let i = 0; i + 3 < au.length; i++) if (au[i] === 0 && au[i + 1] === 0 && au[i + 2] === 1 && (au[i + 3] & 0x1f) === 5) key = true;
    return {data: au, key};
  });
}
