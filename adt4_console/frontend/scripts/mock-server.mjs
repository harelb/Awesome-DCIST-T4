const MIME = {".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".png": "image/png", ".json": "application/json", ".ico": "image/x-icon", ".woff2": "font/woff2"};
function serveStatic(url, res) {
  let p = join(STATIC, decodeURIComponent(url.pathname));
  if (!p.startsWith(STATIC)) return json(res, 403, {detail: "forbidden"});
  if (!existsSync(p) || statSync(p).isDirectory()) p = join(STATIC, "index.html");
  if (!existsSync(p)) {
    res.writeHead(404, {"Content-Type": "text/plain"});
    return res.end("frontend not built: run `npm run build` (or use `npm run dev`)");
  }
  res.writeHead(200, {"Content-Type": MIME[extname(p)] ?? "application/octet-stream"});
  res.end(readFileSync(p));
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  if (!url.pathname.startsWith("/api/")) return serveStatic(url, res);
  for (const rt of routes) {
    if (rt.method !== req.method) continue;
    const m = rt.re.exec(url.pathname);
    if (m) {
      try {
        return await rt.fn(req, res, m, url);
      } catch (e) {
        return json(res, 500, {detail: String(e)});
      }
    }
  }
  json(res, 404, {detail: `mock: no route ${req.method} ${url.pathname}`});
});

